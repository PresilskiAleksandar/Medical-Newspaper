const articlesDir = path.join(__dirname, '..', 'articles');

for (const [catSlug, articles] of Object.entries(articleData)) {
  const dir = path.join(articlesDir, catSlug);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  
  articles.forEach((article, idx) => {
    const n = idx + 1;
    const cluster = article.c.split('/')[1];
    const content = generateArticle(article.t, cluster, catSlug);
    const contentFile = path.join(dir, `article-00${n}-content.txt`);
    fs.writeFileSync(contentFile, content, 'utf8');
    
    const metaFile = path.join(dir, `article-00${n}.json`);
    if (!fs.existsSync(metaFile)) {
      const meta = {
        title: article.t,
        seo_title: article.t.substring(0, 60) + ' | МедИнфо',
        meta_description: article.t.substring(0, 155),
        keywords: [article.t, catSlug, cluster],
        image_prompt: `Medical illustration or photography related to ${article.t}, professional medical visualization, clinical style, 4K resolution`,
      };
      fs.writeFileSync(metaFile, JSON.stringify(meta, null, 2), 'utf8');
    }
  });
}

